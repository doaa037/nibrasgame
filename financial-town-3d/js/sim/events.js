/**
 * يختار حدثاً مناسباً للحالة الراهنة بترجيح الأوزان.
 * نستبعد ما لا تنطبق شروطه وما وقع مؤخّراً حتى لا يتكرّر الحدث نفسه.
 */
export function pickEvent(state, recentIds = []) {
  const pool = EVENTS.filter(e =>
    (!e.requires || e.requires(state)) && !recentIds.includes(e.id));
  if (!pool.length) return null;

  const totalWeight = pool.reduce((sum, e) => sum + e.weight, 0);
  let roll = Math.random() * totalWeight;
  for (const e of pool) {
    roll -= e.weight;
    if (roll <= 0) return e;
  }
  return pool[pool.length - 1];
}
