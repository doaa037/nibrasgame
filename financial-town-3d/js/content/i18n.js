/** يعيد النصّ المناسب للغة الحالية. يقبل مفتاح UI أو كائن {ar,he}. */
export function t(key) {
  const entry = typeof key === 'string' ? UI[key] : key;
  if (!entry) return typeof key === 'string' ? key : '';
  return entry[current] || entry.ar || '';
}

export function getLang() { return current; }
export function getDir()  { return LANGS[current].dir; }
export function list()    { return Object.values(LANGS); }
export function onChange(fn) { listeners.push(fn); }

/** يبدّل اللغة ويحدّث lang/dir/الخط على <html> ثم يُخطر المشتركين */
export function setLang(code) {
  if (!LANGS[code]) return;
  current = code;
  const cfg = LANGS[code];
  const html = document.documentElement;
  html.setAttribute('lang', cfg.code);
  html.setAttribute('dir', cfg.dir);
  html.setAttribute('data-lang', cfg.code);
  html.style.setProperty('--font', cfg.font);
  try { localStorage.setItem('finTown3D.lang', code); } catch (e) { /* وضع خاص */ }
  listeners.forEach(fn => fn(code, cfg));
}

/** اللغة المحفوظة، وإلا لغة المتصفّح، وإلا العربية */
export function detectLang() {
  let saved = null;
  try { saved = localStorage.getItem('finTown3D.lang'); } catch (e) { /* تجاهل */ }
  if (saved && LANGS[saved]) return saved;
  const nav = (navigator.language || 'ar').slice(0, 2);
  return LANGS[nav] ? nav : 'ar';
}
