/** المهمّة النشطة: أوّل مهمّة لم تكتمل بعد */
export function activeQuest(state) {
  return QUESTS.find(q => !q.done(state)) || null;
}

/** فحص الأوسمة المستحقّة؛ يعيد الجديدة فقط ليُعرض إشعارها */
export function checkBadges(state) {
  const fresh = [];
  for (const b of BADGES) {
    if (!state.badges.includes(b.id) && b.check(state)) {
      state.badges.push(b.id);
      fresh.push(b);
    }
  }
  return fresh;
}
